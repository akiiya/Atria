// header 中宽高占位符的偏移量（SOF0 段内）。
// JPEG 的 SOF0 用 2 字节大端表示宽高，缩略图边长不超过 255，
// 因此高位字节恒为 0，实际值写入低位字节。
const (
	strippedHeightOffset = 165 // SOF0 高度字段低位字节（高位在 164）
	strippedWidthOffset  = 167 // SOF0 宽度字段低位字节（高位在 166）
)

// decodeStrippedThumb 将 Telegram 的去头 JPEG 还原为完整 JPEG 字节。
// 数据非法时返回 nil。
func decodeStrippedThumb(data []byte) []byte {
	// 至少需要版本标记 + 宽 + 高
	if len(data) < 3 || data[0] != 0x01 {
		return nil
	}

	out := make([]byte, 0, len(strippedJPEGHeader)+len(data)-3+len(strippedJPEGFooter))
	out = append(out, strippedJPEGHeader...)

	// 写入实际宽高（各 1 字节，因为缩略图边长不会超过 255）
	out[strippedHeightOffset] = data[2]
	out[strippedWidthOffset] = data[1]

	out = append(out, data[3:]...)
	out = append(out, strippedJPEGFooter...)
	return out
}

// strippedThumbDataURI 将去头 JPEG 转为可直接用于 img src 的 data URI。
// 无有效缩略图时返回空字符串。
func strippedThumbDataURI(data []byte) string {
	jpeg := decodeStrippedThumb(data)
	if jpeg == nil {
		return ""
	}
	return "data:image/jpeg;base64," + base64.StdEncoding.EncodeToString(jpeg)
}

// extractPhotoThumbnail 从 Photo 的尺寸列表中提取内嵌缩略图。
// 优先使用 PhotoStrippedSize（去头 JPEG），其次 PhotoCachedSize（完整 JPEG 字节）。
func extractPhotoThumbnail(photo *tg.Photo) string {
	if photo == nil {
		return ""
	}
	for _, size := range photo.Sizes {
		switch s := size.(type) {
		case *tg.PhotoStrippedSize:
			if uri := strippedThumbDataURI(s.Bytes); uri != "" {
				return uri
			}
		case *tg.PhotoCachedSize:
			if len(s.Bytes) > 0 {
				return "data:image/jpeg;base64," + base64.StdEncoding.EncodeToString(s.Bytes)
			}
		}
	}
	return ""
}

// extractDocumentThumbnail 从 Document 的缩略图列表中提取内嵌预览。
// 视频和部分文档类型会携带缩略图。
func extractDocumentThumbnail(doc *tg.Document) string {
	if doc == nil {
		return ""
	}
	for _, size := range doc.Thumbs {
		switch s := size.(type) {
		case *tg.PhotoStrippedSize:
			if uri := strippedThumbDataURI(s.Bytes); uri != "" {
				return uri
			}
		case *tg.PhotoCachedSize:
			if len(s.Bytes) > 0 {
				return "data:image/jpeg;base64," + base64.StdEncoding.EncodeToString(s.Bytes)
			}
		}
	}
	return ""
}
